let currentQuiz = null;
let currentQuestionIndex = 0;
let userAnswers = {};
let timeLeft = 600; // 10 minutes default
let timerInterval = null;
let quizStartTime = null;

// DOM Elements
const quizSelection = document.getElementById('quiz-selection');
const quizTaking = document.getElementById('quiz-taking');
const quizResults = document.getElementById('quiz-results');
const quizTitle = document.getElementById('quiz-title');
const questionIndicator = document.getElementById('question-indicator');
const currentQuestion = document.getElementById('current-question');
const optionsGrid = document.getElementById('options-grid');
const quizTimer = document.getElementById('quiz-timer');
const progressFill = document.getElementById('progress-fill');
const prevBtn = document.getElementById('prev-question-btn');
const nextBtn = document.getElementById('next-question-btn');
const submitBtn = document.getElementById('submit-quiz-btn');

// Initialize
document.addEventListener('DOMContentLoaded', () => {
    setupEventListeners();
});

function setupEventListeners() {
    prevBtn.addEventListener('click', previousQuestion);
    nextBtn.addEventListener('click', nextQuestion);
    submitBtn.addEventListener('click', submitQuiz);
    document.getElementById('retry-quiz-btn').addEventListener('click', retryQuiz);
    document.getElementById('quiz-home-btn').addEventListener('click', () => window.location.href = 'index.html');
}

function selectSubject(subject) {
    const quizzes = quizzesData[subject];
    if (!quizzes || quizzes.length === 0) return;

    // Randomly select one quiz from the subject
    currentQuiz = quizzes[Math.floor(Math.random() * quizzes.length)];
    startQuiz();
}

function startQuiz() {
    userAnswers = {};
    currentQuestionIndex = 0;
    timeLeft = currentQuiz.questions.length * 60; // 1 minute per question
    quizStartTime = Date.now();

    quizSelection.style.display = 'none';
    quizTaking.style.display = 'block';
    quizResults.style.display = 'none';

    quizTitle.textContent = currentQuiz.title;
    displayQuestion();
    updateTimer();
    timerInterval = setInterval(updateTimer, 1000);
}

function displayQuestion() {
    const question = currentQuiz.questions[currentQuestionIndex];
    const totalQuestions = currentQuiz.questions.length;

    questionIndicator.textContent = `Question ${currentQuestionIndex + 1} of ${totalQuestions}`;
    currentQuestion.textContent = question.q;

    optionsGrid.innerHTML = '';
    question.options.forEach((option, index) => {
        const optionDiv = document.createElement('div');
        optionDiv.className = 'option-card';
        const isSelected = userAnswers[currentQuestionIndex] === index;
        if (isSelected) optionDiv.classList.add('selected');

        optionDiv.innerHTML = `
            <input type="radio" name="option" value="${index}" ${isSelected ? 'checked' : ''}>
            <label>${option}</label>
        `;

        optionDiv.addEventListener('click', () => {
            userAnswers[currentQuestionIndex] = index;
            displayQuestion();
        });

        optionsGrid.appendChild(optionDiv);
    });

    // Update progress bar
    const progress = ((currentQuestionIndex + 1) / totalQuestions) * 100;
    progressFill.style.width = progress + '%';

    // Update button states
    prevBtn.disabled = currentQuestionIndex === 0;
    if (currentQuestionIndex === totalQuestions - 1) {
        nextBtn.style.display = 'none';
        submitBtn.style.display = 'inline-block';
    } else {
        nextBtn.style.display = 'inline-block';
        submitBtn.style.display = 'none';
    }
}

function previousQuestion() {
    if (currentQuestionIndex > 0) {
        currentQuestionIndex--;
        displayQuestion();
    }
}

function nextQuestion() {
    if (currentQuestionIndex < currentQuiz.questions.length - 1) {
        currentQuestionIndex++;
        displayQuestion();
    }
}

function updateTimer() {
    timeLeft--;
    const mins = Math.floor(timeLeft / 60);
    const secs = timeLeft % 60;
    quizTimer.textContent = `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;

    if (timeLeft < 0) {
        clearInterval(timerInterval);
        alert('Time is up!');
        submitQuiz();
    }
}

function submitQuiz() {
    clearInterval(timerInterval);

    let correct = 0;
    let unanswered = 0;

    currentQuiz.questions.forEach((q, i) => {
        if (userAnswers[i] === undefined) {
            unanswered++;
        } else if (userAnswers[i] === q.answer) {
            correct++;
        }
    });

    const total = currentQuiz.questions.length;
    const incorrect = total - correct - unanswered;
    const percentage = Math.round((correct / total) * 100);

    // Save result
    const quizHistory = JSON.parse(localStorage.getItem('quiz-history') || '[]');
    quizHistory.push({
        title: currentQuiz.title,
        score: correct,
        total: total,
        timestamp: new Date().toLocaleString()
    });
    localStorage.setItem('quiz-history', JSON.stringify(quizHistory));

    showResults(correct, total, percentage, incorrect, unanswered);
}

function showResults(correct, total, percentage, incorrect, unanswered) {
    quizTaking.style.display = 'none';
    quizResults.style.display = 'block';

    document.getElementById('quiz-score-percentage').textContent = percentage + '%';
    document.getElementById('quiz-score-value').textContent = `${correct}/${total}`;
    document.getElementById('quiz-correct-count').textContent = correct;
    document.getElementById('quiz-incorrect-count').textContent = incorrect;
    document.getElementById('quiz-unanswered-count').textContent = unanswered;

    // Build review
    const reviewHTML = currentQuiz.questions.map((q, i) => {
        const userAnswer = userAnswers[i];
        const isCorrect = userAnswer === q.answer;
        const status = userAnswer === undefined ? 'Unanswered' : (isCorrect ? '✓ Correct' : '✗ Incorrect');
        const statusClass = userAnswer === undefined ? 'unanswered' : (isCorrect ? 'correct' : 'incorrect');

        return `
            <div class="review-item ${statusClass}">
                <p><strong>Q${i + 1}: ${q.q}</strong></p>
                <p>Your answer: ${userAnswer !== undefined ? q.options[userAnswer] : 'Not answered'}</p>
                <p>Correct answer: ${q.options[q.answer]}</p>
                <p class="status">${status}</p>
            </div>
        `;
    }).join('');

    document.getElementById('quiz-review-container').innerHTML = reviewHTML;
}

function retryQuiz() {
    quizSelection.style.display = 'block';
    quizTaking.style.display = 'none';
    quizResults.style.display = 'none';
    startQuiz();
}
